def _build_charts(results: list[BenchmarkResult]) -> str:
    names = [r.name[:15] for r in results]
    means = [r.latency.mean_ms for r in results]
    p95s = [r.latency.p95_ms for r in results]

    html = ""
    if len(results) >= 1:
        latency_chart = bar_chart(names, means, title="Mean Latency by Benchmark", ylabel="ms")
        html += f'<div class="chart">{latency_chart}</div>'

    if len(results) >= 2:
        compare_chart = multi_bar_chart(
            names,
            [means, p95s],
            series_labels=["Mean", "P95"],
            title="Latency Comparison: Mean vs P95",
            ylabel="ms",
        )
        html += f'<div class="chart">{compare_chart}</div>'

    return html


def _build_table(results: list[BenchmarkResult]) -> str:
    rows = []
    for r in results:
        rows.append(
            f"<tr><td>{r.name}</td><td>{r.suite}</td>"
            f"<td>{r.latency.mean_ms:.1f}</td><td>{r.latency.p50_ms:.1f}</td>"
            f"<td>{r.latency.p95_ms:.1f}</td><td>{r.latency.p99_ms:.1f}</td>"
            f"<td>{r.throughput_qps:.1f}</td>"
            f"<td>{r.recall_at_k:.3f}</td></tr>"
        )
    return "\n".join(rows)


def _build_summary(results: list[BenchmarkResult]) -> str:
    if not results:
        return '<div class="summary"><div class="card"><div class="value">0</div><div class="label">Benchmarks</div></div></div>'

    total = len(results)
    avg_latency = sum(r.latency.mean_ms for r in results) / total
    total_qps = sum(r.throughput_qps for r in results)

    suites = set(r.suite for r in results)

    return f"""<div class="summary">
<div class="card"><div class="value">{total}</div><div class="label">Benchmarks</div></div>
<div class="card"><div class="value">{avg_latency:.1f}</div><div class="label">Avg Latency (ms)</div></div>
<div class="card"><div class="value">{total_qps:.0f}</div><div class="label">Total Throughput (QPS)</div></div>
<div class="card"><div class="value">{len(suites)}</div><div class="label">Suites</div></div>
</div>"""
